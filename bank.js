  // 採点用の正規化。添字(₂)→数字、上付き(²⁺)→「^2+」、全角→半角、空白除去、中点の統一。
  const SUP = { "⁰": "0", "¹": "1", "²": "2", "³": "3", "⁴": "4", "⁵": "5", "⁶": "6", "⁷": "7", "⁸": "8", "⁹": "9", "⁺": "+", "⁻": "-" };
  function norm(s) {
    s = String(s).replace(/[⁰¹²³⁴⁵⁶⁷⁸⁹⁺⁻]+/g, m => "^" + Array.from(m).map(c => SUP[c]).join(""));
    s = s.normalize("NFKC").replace(/[−‐‑–—ー]/g, "-").replace(/[・･∙•⋅.]/g, "·").replace(/\s+/g, "");
    if (!s.includes("^")) s = s.replace(/([+-])$/, "^$1"); // 1価の電荷は半角の + - でも受け付ける（NH4+ など）
    return s;
  }
  // 化学式の採点。係数も含めて判定する（正解が 2NO₂ なら NO₂ は不正解）。係数1は書いても省略してもよい。
  // 反応式全体（2NO+O2→2NO2）を書いた場合は、右辺のいずれかの項が正解と一致すれば正解にする。
  function judgeFormula(input, p) {
    const answers = [p.a].concat(p.alts || []).map(norm);
    const stripCoef = t => t.replace(/^1(?=[A-Za-z(\[])/, "");
    const x = norm(input);
    if (!x) return false;
    const cands = [x, stripCoef(x)];
    if (/[→=]|->/.test(x)) {
      const rhs = x.split(/→|=|->/).pop();
      cands.push(rhs, stripCoef(rhs));
      rhs.split(/\+(?![\^])/).forEach(t => cands.push(stripCoef(t))); // 右辺の各項（電荷の + は区切らない）
    }
    return cands.some(c => answers.includes(c));
  }
  // 入力中の文字列を表示用にする。元素記号や ) ] のあとの数字は添字にする（係数は添字にしない）。
  function fmtFormula(raw) {
    const esc = c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;" }[c] || c);
    let out = "", prev = "", inSub = false;
    for (const c of Array.from(String(raw))) {
      if (/[0-9]/.test(c) && (inSub || /[A-Za-z)\]]/.test(prev))) { out += (inSub ? "" : "<sub>") + c; inSub = true; }
      else { if (inSub) out += "</sub>"; inSub = false; out += esc(c); }
      prev = c;
    }
    return out + (inSub ? "</sub>" : "");
  }

